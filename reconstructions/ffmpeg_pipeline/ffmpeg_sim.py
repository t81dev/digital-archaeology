# 4. Pipeline Orchestration & CLI Translator
# ============================================================================

class FFmpegPipeline:
    """
    Orchestrates the 5-stage media transcode loop.
    """
    def __init__(
        self,
        input_filename: str,
        output_filename: str,
        video_codec: str = "libx264",
        filter_spec: str = "",
        registry: Optional[CodecContainerRegistry] = None
    ):
        self.registry = registry if registry else CodecContainerRegistry()
        self.demuxer = Demuxer(input_filename, self.registry)
        self.decoder = Decoder("h264", self.registry)
        self.filter_graph = FilterGraph(filter_spec)
        self.encoder = Encoder(video_codec, self.registry)
        self.muxer = Muxer(output_filename, self.registry)

    def run(self) -> int:
        """Executes full 5-stage loop until end of stream."""
        frames_processed = 0
        while True:
            # 1. Demux
            pkt = self.demuxer.read_packet()
            if not pkt:
                break

            # 2. Decode
            frame = self.decoder.send_packet(pkt)
            if not frame:
                continue

            # 3. Filter
            filtered_frame = self.filter_graph.process_frame(frame)

            # 4. Encode
            enc_pkt = self.encoder.send_frame(filtered_frame)

            # 5. Mux
            if enc_pkt:
                self.muxer.write_packet(enc_pkt)
                frames_processed += 1

        return frames_processed


class FFmpegCLITranslator:
    """
    Parses CLI command string expressions into an executed FFmpegPipeline.
    Example: 'ffmpeg -i input.mp4 -vf scale=1280:720 -c:v libx264 output.mkv'
    """
    def __init__(self, registry: Optional[CodecContainerRegistry] = None):
        self.registry = registry if registry else CodecContainerRegistry()

    def parse_and_execute(self, command_line: str) -> Tuple[FFmpegPipeline, int]:
        tokens = command_line.strip().split()
        if not tokens or tokens[0] != "ffmpeg":
            raise ValueError("Command must start with 'ffmpeg'")

        input_file = ""
        output_file = ""
        video_codec = "libx264"
        filter_spec = ""

        i = 1
        while i < len(tokens):
            tok = tokens[i]
            if tok == "-i" and i + 1 < len(tokens):
                input_file = tokens[i + 1]
                i += 2
            elif tok in ("-vf", "-filter:v", "-filter_complex") and i + 1 < len(tokens):
                filter_spec = tokens[i + 1]
                i += 2
            elif tok in ("-c:v", "-vcodec", "-codec:v") and i + 1 < len(tokens):
                video_codec = tokens[i + 1]
                i += 2
            elif not tok.startswith("-") and i == len(tokens) - 1:
                output_file = tok
                i += 1
            else:
                i += 1

        if not input_file or not output_file:
            raise ValueError("CLI command missing input or output file specifier")

        pipeline = FFmpegPipeline(
            input_filename=input_file,
            output_filename=output_file,
            video_codec=video_codec,
            filter_spec=filter_spec,
            registry=self.registry
        )
        processed = pipeline.run()
        return pipeline, processed
